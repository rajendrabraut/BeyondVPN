//! Rendering of wg-quick / WireGuard-for-Windows compatible client configs.

use crate::cidr::{self, Cidr4};
use crate::keys;
use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct TunnelConfig {
    pub private_key: String,
    /// Interface address, e.g. `10.8.0.5/32`.
    pub address: String,
    #[serde(default)]
    pub dns: Vec<String>,
    #[serde(default)]
    pub mtu: Option<u16>,
    pub peer_public_key: String,
    #[serde(default)]
    pub preshared_key: Option<String>,
    /// `host:port` of the gateway.
    pub endpoint: String,
    #[serde(default = "default_allowed")]
    pub allowed_ips: Vec<String>,
    #[serde(default = "default_keepalive")]
    pub persistent_keepalive: u16,
}

fn default_allowed() -> Vec<String> {
    vec!["0.0.0.0/0".into(), "::/0".into()]
}

fn default_keepalive() -> u16 {
    25
}

#[derive(Debug, Clone, Default, Serialize, Deserialize, PartialEq, Eq)]
pub struct ClientOptions {
    /// Block all traffic outside the tunnel (kill switch).
    #[serde(default)]
    pub kill_switch: bool,
    /// Keep LAN reachable while connected.
    #[serde(default)]
    pub allow_lan: bool,
    /// Extra IPv4 networks to route outside the tunnel (split tunnelling).
    #[serde(default)]
    pub exclude_routes: Vec<String>,
    /// Target platform: "windows", "linux", "macos", "android", "ios".
    #[serde(default)]
    pub platform: String,
}

#[derive(Debug, thiserror::Error, PartialEq, Eq)]
pub enum ConfigError {
    #[error("invalid key: {0}")]
    Key(&'static str),
    #[error("invalid field {0}")]
    Field(&'static str),
}

fn safe_token(s: &str) -> bool {
    !s.is_empty()
        && s.chars().all(|c| c.is_ascii_alphanumeric() || ".:-_[]/".contains(c))
}

impl TunnelConfig {
    pub fn validate(&self) -> Result<(), ConfigError> {
        keys::validate_key(&self.private_key).map_err(|_| ConfigError::Key("private_key"))?;
        keys::validate_key(&self.peer_public_key).map_err(|_| ConfigError::Key("peer_public_key"))?;
        if let Some(psk) = &self.preshared_key {
            keys::validate_key(psk).map_err(|_| ConfigError::Key("preshared_key"))?;
        }
        // Guard against config-file injection through newlines etc.
        if !safe_token(&self.address) {
            return Err(ConfigError::Field("address"));
        }
        if !safe_token(&self.endpoint) || !self.endpoint.contains(':') {
            return Err(ConfigError::Field("endpoint"));
        }
        if self.dns.iter().any(|d| !safe_token(d)) {
            return Err(ConfigError::Field("dns"));
        }
        if self.allowed_ips.iter().any(|d| !safe_token(d)) {
            return Err(ConfigError::Field("allowed_ips"));
        }
        Ok(())
    }

    /// Effective AllowedIPs after applying split tunnelling options.
    pub fn effective_allowed_ips(&self, opts: &ClientOptions) -> Result<Vec<String>, ConfigError> {
        let mut excludes: Vec<Cidr4> = Vec::new();
        if opts.allow_lan {
            excludes.extend(cidr::lan_ranges());
        }
        for r in &opts.exclude_routes {
            excludes.push(r.parse().map_err(|_| ConfigError::Field("exclude_routes"))?);
        }
        if excludes.is_empty() {
            return Ok(self.allowed_ips.clone());
        }
        let v4: Vec<Cidr4> = self
            .allowed_ips
            .iter()
            .filter(|s| !s.contains(':'))
            .map(|s| s.parse().map_err(|_| ConfigError::Field("allowed_ips")))
            .collect::<Result<_, _>>()?;
        let mut out: Vec<String> = cidr::subtract(&v4, &excludes).iter().map(|c| c.to_string()).collect();
        out.extend(self.allowed_ips.iter().filter(|s| s.contains(':')).cloned());
        Ok(out)
    }

    /// Render the INI file understood by wg-quick and WireGuard for Windows.
    pub fn render(&self, opts: &ClientOptions) -> Result<String, ConfigError> {
        self.validate()?;
        let allowed = self.effective_allowed_ips(opts)?;
        let mut s = String::new();
        s.push_str("# Generated by Beyond VPN. Do not share: contains a private key.\n");
        s.push_str("[Interface]\n");
        s.push_str(&format!("PrivateKey = {}\n", self.private_key));
        s.push_str(&format!("Address = {}\n", self.address));
        if !self.dns.is_empty() {
            s.push_str(&format!("DNS = {}\n", self.dns.join(", ")));
        }
        if let Some(mtu) = self.mtu {
            s.push_str(&format!("MTU = {mtu}\n"));
        }
        if opts.kill_switch && opts.platform == "linux" {
            // nftables kill switch: drop anything not going through the tunnel
            // or to the gateway endpoint (pattern used by Mullvad/Proton CLI).
            s.push_str("PostUp = nft add table inet beyond_ks; nft add chain inet beyond_ks out '{ type filter hook output priority 0; policy drop; }'; nft add rule inet beyond_ks out oifname \"lo\" accept; nft add rule inet beyond_ks out oifname \"%i\" accept; nft add rule inet beyond_ks out meta mark 51820 accept\n");
            s.push_str("PreDown = nft delete table inet beyond_ks\n");
        }
        s.push_str("\n[Peer]\n");
        s.push_str(&format!("PublicKey = {}\n", self.peer_public_key));
        if let Some(psk) = &self.preshared_key {
            s.push_str(&format!("PresharedKey = {psk}\n"));
        }
        s.push_str(&format!("AllowedIPs = {}\n", allowed.join(", ")));
        s.push_str(&format!("Endpoint = {}\n", self.endpoint));
        if self.persistent_keepalive > 0 {
            s.push_str(&format!("PersistentKeepalive = {}\n", self.persistent_keepalive));
        }
        Ok(s)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample() -> TunnelConfig {
        let c = keys::generate_keypair();
        let s = keys::generate_keypair();
        TunnelConfig {
            private_key: c.private_key,
            address: "10.8.0.2/32".into(),
            dns: vec!["10.8.0.1".into()],
            mtu: Some(1420),
            peer_public_key: s.public_key,
            preshared_key: Some(keys::generate_preshared_key()),
            endpoint: "vpn.example.com:51820".into(),
            allowed_ips: default_allowed(),
            persistent_keepalive: 25,
        }
    }

    #[test]
    fn renders_full_tunnel() {
        let out = sample().render(&ClientOptions::default()).unwrap();
        assert!(out.contains("AllowedIPs = 0.0.0.0/0, ::/0"));
        assert!(out.contains("DNS = 10.8.0.1"));
        assert!(out.contains("PresharedKey = "));
        assert!(!out.contains("PostUp"));
    }

    #[test]
    fn linux_kill_switch_adds_nft_rules() {
        let opts = ClientOptions { kill_switch: true, platform: "linux".into(), ..Default::default() };
        let out = sample().render(&opts).unwrap();
        assert!(out.contains("PostUp = nft"));
        assert!(out.contains("PreDown = nft delete table inet beyond_ks"));
    }

    #[test]
    fn allow_lan_removes_private_ranges() {
        let opts = ClientOptions { allow_lan: true, ..Default::default() };
        let ips = sample().effective_allowed_ips(&opts).unwrap();
        assert!(!ips.contains(&"0.0.0.0/0".to_string()));
        assert!(ips.contains(&"::/0".to_string()));
        assert!(ips.contains(&"8.0.0.0/7".to_string()));
    }

    #[test]
    fn rejects_injection() {
        let mut c = sample();
        c.endpoint = "evil:1\nPostUp = rm -rf /".into();
        assert_eq!(c.render(&ClientOptions::default()), Err(ConfigError::Field("endpoint")));
        let mut c = sample();
        c.dns = vec!["1.1.1.1\n[Peer]".into()];
        assert_eq!(c.validate(), Err(ConfigError::Field("dns")));
        let mut c = sample();
        c.private_key = "short".into();
        assert_eq!(c.validate(), Err(ConfigError::Key("private_key")));
    }
}
